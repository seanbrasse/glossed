-- existing types with new ones where the list had no home. TWO LEVELS,
-- finally using 0046's parent_id: the TOP level stays the rankable set —
-- ladders, anchors, wear-in and every picker key off it (DataKit's
-- categories() pins parent_id is null since the guard PR) — and the ~200
-- LEAVES are the fine-grained product-type vocabulary underneath.
-- Products keep attaching to the top level; a leaf never fragments a
-- ladder. Idempotent by slug, 0046's own rule; leaf slugs are prefixed
